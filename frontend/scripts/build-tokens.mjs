// Renders src/theme/tokens.json (the single source of truth for colours, fonts, radii and
// shadows) into the files the apps read:
//   src/theme/tokens.css   --vp-* CSS variables: :root = default theme, [data-theme="x"] per theme
//   src/theme/tokens.js    the same values as a JS object, for canvas/three/recharts/mermaid
//   <mobile>/src/theme/tokens.js   with --mobile <mobile checkout dir>
//
//   bun scripts/build-tokens.mjs                 write the web files
//   bun scripts/build-tokens.mjs --check         exit 1 if the web files are stale
//   bun scripts/build-tokens.mjs --mobile ../mobile

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const THEME_DIR = join(ROOT, "src/theme");
const HEADER =
	"GENERATED by frontend/scripts/build-tokens.mjs from frontend/src/theme/tokens.json — do not edit.";

const args = process.argv.slice(2);
const check = args.includes("--check");
const mobileIdx = args.indexOf("--mobile");
const mobileDir = mobileIdx === -1 ? null : resolve(args[mobileIdx + 1] ?? "");

const spec = JSON.parse(readFileSync(join(THEME_DIR, "tokens.json"), "utf8"));
const { primitives, themes, defaultTheme } = spec;
const staticTokens = spec.static;

if (!themes[defaultTheme])
	throw new Error(`defaultTheme "${defaultTheme}" is not in themes`);

const resolveRef = (value, where) =>
	value.replace(/\{([a-z0-9-]+)\}/g, (_, name) => {
		if (!(name in primitives))
			throw new Error(`${where}: unknown primitive {${name}}`);
		return primitives[name];
	});

const resolved = Object.fromEntries(
	Object.entries(themes).map(([id, theme]) => [
		id,
		{
			...theme,
			tokens: Object.fromEntries(
				Object.entries(theme.tokens).map(([k, v]) => [
					k,
					resolveRef(v, `${id}.${k}`),
				]),
			),
		},
	]),
);

// Every theme must define the same token set, or a theme switch leaves holes.
const expected = Object.keys(resolved[defaultTheme].tokens).sort().join();
for (const [id, theme] of Object.entries(resolved)) {
	if (Object.keys(theme.tokens).sort().join() !== expected) {
		throw new Error(
			`theme "${id}" does not define the same tokens as "${defaultTheme}"`,
		);
	}
}

const camel = (s) => s.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
const cssVars = (obj) =>
	Object.entries(obj)
		.map(([k, v]) => `\t--vp-${k}: ${v};`)
		.join("\n");

function renderCss() {
	const blocks = Object.entries(resolved).map(([id, theme]) => {
		const selector =
			id === defaultTheme
				? `:root,\n[data-theme="${id}"]`
				: `[data-theme="${id}"]`;
		return `${selector} {\n\tcolor-scheme: ${theme.scheme};\n${cssVars(theme.tokens)}\n}`;
	});
	return [
		`/* ${HEADER} */`,
		`:root {\n${cssVars(staticTokens)}\n}`,
		...blocks,
	].join("\n\n");
}

const jsObject = (obj, indent) =>
	`{\n${Object.entries(obj)
		.map(([k, v]) => `${indent}\t${camel(k)}: ${JSON.stringify(v)},`)
		.join("\n")}\n${indent}}`;

function renderWebJs() {
	const themeEntries = Object.entries(resolved)
		.map(
			([id, t]) =>
				`\t${JSON.stringify(id)}: {\n\t\tlabel: ${JSON.stringify(t.label)},\n\t\tscheme: ${JSON.stringify(t.scheme)},\n\t\ttokens: ${jsObject(t.tokens, "\t\t")},\n\t},`,
		)
		.join("\n");
	return `// ${HEADER}

export const defaultTheme = ${JSON.stringify(defaultTheme)};

export const themes = {
${themeEntries}
};

export const staticTokens = ${jsObject(staticTokens, "")};
`;
}

// Mobile (React Native) only takes colours: fonts and shadows are platform-specific there.
function renderMobileJs() {
	const themeEntries = Object.entries(resolved)
		.map(([id, t]) => {
			const body = Object.entries(t.tokens)
				.map(([k, v]) => `\t\t\t${camel(k)}: ${JSON.stringify(v)},`)
				.join("\n");
			return `\t${JSON.stringify(id)}: {\n\t\tlabel: ${JSON.stringify(t.label)},\n\t\tscheme: ${JSON.stringify(t.scheme)},\n\t\tcolors: {\n${body}\n\t\t},\n\t},`;
		})
		.join("\n");
	return `// ${HEADER}

export const defaultTheme = ${JSON.stringify(defaultTheme)};

export const themes = {
${themeEntries}
};
`;
}

const outputs = [
	[join(THEME_DIR, "tokens.css"), `${renderCss()}\n`],
	[join(THEME_DIR, "tokens.js"), renderWebJs()],
];
if (mobileDir)
	outputs.push([join(mobileDir, "src/theme/tokens.js"), renderMobileJs()]);

let stale = false;
for (const [file, content] of outputs) {
	let current = null;
	try {
		current = readFileSync(file, "utf8");
	} catch {}
	if (current === content) continue;
	if (check) {
		console.error(`✗ stale: ${file} — run bun run theme:build`);
		stale = true;
	} else {
		writeFileSync(file, content);
		console.log(`✓ wrote ${file}`);
	}
}
if (stale) process.exit(1);
